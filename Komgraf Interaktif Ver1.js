		// =========================================
		// 15. BERSIHKAN INPUT
		// =========================================
		
		function bersihkanInputEssay() {
		
			if (!textareaEssay) return;
		
			simpanJawabanEssay();
		
			// Hapus event input
			textareaEssay.removeEventListener(
				"input",
				simpanJawabanEssay
			);
		
			areaInputEssay.removeEventListener(
				"click",
				aktifkanInputEssay
			);
		
			// Hapus textarea HTML
			if (textareaEssay.parentNode) {
				textareaEssay.parentNode.removeChild(textareaEssay);
			}
		
			// Hapus event tombol
			tombolKembali.removeEventListener(
				"click",
				handlerKembaliEssay
			);
		
			tombolLanjut.removeEventListener(
				"click",
				handlerNextEssay
			);
		
			tombolSkor.removeEventListener(
				"click",
				handlerSkorEssay
			);
		
			// Hapus event browser
			window.removeEventListener(
				"resize",
				handlerResizeEssay
			);
		
			window.removeEventListener(
				"scroll",
				handlerScrollEssay
			);
		
			// Pulihkan tulisan placeholder
			if (teksPlaceholder) {
				teksPlaceholder.text = placeholderAsli;
			}
		
			console.log("Input Essay dibersihkan.");
		}
		
		
